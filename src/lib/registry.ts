const BY_KEY = new Map(RESOURCES.map((r) => [r.key, r]));
const BY_MODEL = new Map(RESOURCES.map((r) => [r.model, r]));

export const getResource = (key: string): ResourceDef | undefined => BY_KEY.get(key);
export const getResourceByModel = (model: string): ResourceDef | undefined => BY_MODEL.get(model);

export const RESOURCE_KEYS = RESOURCES.map((r) => r.key);

/** Toutes les permissions declenchees par les ressources : <resource>:read ... */
export const PERMISSION_ACTIONS = ["read", "create", "update", "delete"] as const;

export const permissionCode = (resource: string, action: string) => `${resource}:${action}`;

/** Libelle lisible d'une permission. */
export function permissionLabel(code: string): string {
  const [resource, action] = code.split(":");
  const res = getResource(resource);
  const resourceLabel = res ? res.label.toLowerCase() : resource;
  const actions: Record<string, string> = {
    read: "consulter",
    create: "creer",
    update: "modifier",
    delete: "supprimer",
  };
  return `${actions[action] ?? action} : ${resourceLabel}`;
}
