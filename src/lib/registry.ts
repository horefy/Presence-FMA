/** Retrouve le champ (cle etrangere) correspondant a une colonne de relation. */
export function relationFieldFor(
  resource: ResourceDef,
  column: string,
): FieldDef | undefined {
  return resource.fields.find(
    (f) => f.relation && RELATION_PROPERTY[f.name] === column,
  );
}

